#include "ItemUsed.hpp"
#include "PacketReader.hpp"

Packet::ItemUsed::Data Packet::ItemUsed::GetResult(const std::vector<uint8_t> &inputData)
{
    Reader reader(inputData);
    Data data{};
    data.PlayerId = reader.Read<int32_t>();
    data.Item = reader.ReadDotNetString();
    data.PositionX = reader.Read<float>();
    data.PositionY = reader.Read<float>();
    data.PositionZ = reader.Read<float>();
    return data;
}
